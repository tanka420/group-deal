const fs = require("fs");
const path = require("path");

function generateAbi() {
  const artifactPath = path.resolve(__dirname, "../contracts/artifacts/contracts/GroupDealHub.sol/GroupDealHub.json");
  if (!fs.existsSync(artifactPath)) {
    console.error(`[ABI Generator] Artifact not found at ${artifactPath}. Please run 'npm run compile' first.`);
    process.exit(1);
  }

  const hubArtifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  const { abi, bytecode } = hubArtifact;

  // 1. Output TypeScript file for backend
  const backendContractsDir = path.resolve(__dirname, "../backend/src/contracts");
  if (!fs.existsSync(backendContractsDir)) {
    fs.mkdirSync(backendContractsDir, { recursive: true });
  }

  const tsContent = `// AUTO-GENERATED FROM contracts/artifacts/contracts/GroupDealHub.sol/GroupDealHub.json
// DO NOT EDIT MANUALLY. Generated by scripts/generate_abi.cjs.

export const HUB_ABI = ${JSON.stringify(abi, null, 2)} as const;

export const HUB_BYTECODE = "${bytecode}" as const;
`;

  fs.writeFileSync(path.join(backendContractsDir, "hubAbi.ts"), tsContent, "utf8");
  console.log(`[ABI Generator] Successfully generated ${path.join(backendContractsDir, "hubAbi.ts")}`);

  // 2. Output TypeScript/JS file for frontend
  const frontendContractsDir = path.resolve(__dirname, "../frontend/src/contracts");
  if (!fs.existsSync(frontendContractsDir)) {
    fs.mkdirSync(frontendContractsDir, { recursive: true });
  }

  fs.writeFileSync(path.join(frontendContractsDir, "hubAbi.ts"), tsContent, "utf8");
  console.log(`[ABI Generator] Successfully generated ${path.join(frontendContractsDir, "hubAbi.ts")}`);
}

if (require.main === module) {
  generateAbi();
}

module.exports = { generateAbi };
